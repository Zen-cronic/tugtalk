import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { Store } from '../src/store.mjs';
mkdirSync('.data',{recursive:true,mode:0o700});
if(existsSync('.data/operator-token.txt')) throw new Error('Already configured; refusing to replace credentials.');
const store=new Store('.data/connector.sqlite');
const token=randomBytes(32).toString('base64url');
store.addToken(token,'synthetic-operator'); store.seed('synthetic-operator');
writeFileSync('.data/operator-token.txt',token,{mode:0o600}); store.close();
console.log('Created synthetic account and two fixture sessions. Credential saved privately to .data/operator-token.txt; not printed.');
